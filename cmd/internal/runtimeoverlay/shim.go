package runtimeoverlay

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// goShimSubcommands are the go subcommands the overlay is injected into.
//
// The list is a closed set on purpose. `go env`, `go version` and `go mod` are NOT in it: they
// are what gomobile uses to DISCOVER the environment (GOMODCACHE, GOMOD, the tool version), and
// a shim that answered those differently would corrupt the discovery it depends on. The
// compiling subcommands are the ones whose output is a package.
var goShimSubcommands = []string{"build", "install", "list", "test", "vet", "run"}

// WriteGoShim writes a `go` executable that injects the overlay into the compiling subcommands
// and passes everything else through untouched, returning the directory to put on PATH.
//
// # Why a shim rather than a flag
//
// gomobile's `bind` has no overlay flag and no environment variable for one; its inner build is
// `exec.Command("go", "build", ...)`, resolved through PATH (cmd/gomobile/build.go:318,
// bind_iosapp.go:335). A PATH entry ahead of the real toolchain is therefore the only injection
// point that does not patch gomobile itself, and it is scoped: the shim is in the environment of
// ONE subprocess, so the Android build and every other command in the same run are unaffected.
//
// # What it must not do
//
// The overlay path is embedded at write time and shell-quoted, so no caller-supplied string
// reaches a shell. The shim records each injection, which is how the builder proves the flag
// rode in rather than assuming it: an overlay that was prepared and never used would otherwise
// look exactly like one that worked, until somebody read the marker out of the artifact.
func WriteGoShim(dir, realGo, overlayJSON, injectedLog string) (string, error) {
	if realGo == "" || overlayJSON == "" {
		return "", fmt.Errorf("runtime overlay: the go shim needs both the real go and the overlay path")
	}
	binDir := filepath.Join(dir, "bin")
	if err := os.MkdirAll(binDir, 0o755); err != nil {
		return "", fmt.Errorf("runtime overlay: create %s: %w", binDir, err)
	}
	var script strings.Builder
	script.WriteString("#!/bin/sh\n")
	script.WriteString("# Generated by cmd/internal/runtimeoverlay for one libbox build.\n")
	script.WriteString("# Injects -overlay into the go subcommands that compile, and only those.\n")
	script.WriteString("real=" + shellQuote(realGo) + "\n")
	script.WriteString("overlay=" + shellQuote(overlayJSON) + "\n")
	script.WriteString("log=" + shellQuote(injectedLog) + "\n")
	script.WriteString("case \"$1\" in\n")
	script.WriteString("  " + strings.Join(goShimSubcommands, "|") + ")\n")
	script.WriteString("    sub=\"$1\"; shift\n")
	script.WriteString("    printf '%s\\n' \"$sub\" >> \"$log\"\n")
	script.WriteString("    exec \"$real\" \"$sub\" \"-overlay=$overlay\" \"$@\"\n")
	script.WriteString("    ;;\n")
	script.WriteString("esac\n")
	script.WriteString("exec \"$real\" \"$@\"\n")
	path := filepath.Join(binDir, "go")
	if err := os.WriteFile(path, []byte(script.String()), 0o755); err != nil {
		return "", fmt.Errorf("runtime overlay: write %s: %w", path, err)
	}
	return binDir, nil
}

// GoShimSubcommands is the closed set the shim injects into, for tests and reports.
func GoShimSubcommands() []string {
	return append([]string{}, goShimSubcommands...)
}

// SetShimDir records where the shim was written, so the overlay can be cleaned up with it.
func (o *Overlay) SetShimDir(dir string) {
	o.shimDir = dir
}

// ShimDir is the directory that must lead PATH for the overlay to reach the compiler.
func (o *Overlay) ShimDir() string {
	return o.shimDir
}

// WithShimPath returns env with the shim directory first on PATH.
//
// PATH is replaced rather than appended because the shim only wins if it is found before the
// real toolchain; appending it would mean the overlay silently did nothing.
func WithShimPath(env []string, binDir string) []string {
	separator := string(os.PathListSeparator)
	out := make([]string, 0, len(env)+1)
	found := false
	for _, entry := range env {
		if strings.HasPrefix(entry, "PATH=") {
			out = append(out, "PATH="+binDir+separator+strings.TrimPrefix(entry, "PATH="))
			found = true
			continue
		}
		out = append(out, entry)
	}
	if !found {
		out = append(out, "PATH="+binDir)
	}
	return out
}

// EnvValue reads one NAME=value entry out of an environment slice.
func EnvValue(env []string, name string) string {
	prefix := name + "="
	for _, entry := range env {
		if strings.HasPrefix(entry, prefix) {
			return strings.TrimPrefix(entry, prefix)
		}
	}
	return ""
}

// CheckGoFlagsHasNoOverlay refuses an environment whose go flags already decide how the runtime is
// compiled.
//
// Two cases, both about the same thing: the overlay must be the ONLY thing that decides, or the
// artifact's marker would name a plan that did not compile it.
//
//   - GOFLAGS carrying `-overlay` means two overlays, and which one wins depends on argument
//     order.
//   - GOFLAGS appearing more than once is worse, because it is silent: execve keeps both entries
//     and getenv (and therefore the go command) returns the FIRST, so a second assignment appended
//     by anything from a wrapper script to a CI `env:` block is ignored - or, read the other way,
//     an overlay appended that way never takes effect while the build looks configured correctly.
//     This was found by the test below passing on one host and failing on another purely because
//     the second host exported an empty GOFLAGS.
func CheckGoFlagsHasNoOverlay(env []string) error {
	values := EnvValues(env, "GOFLAGS")
	if len(values) > 1 {
		return fmt.Errorf(
			"runtime overlay: GOFLAGS appears %d times in the environment (%q). execve keeps every entry and the go "+
				"command reads the first, so the later ones are silently ignored; a build that cannot say which flags it "+
				"compiled with must stop rather than guess", len(values), strings.Join(values, `", "`))
	}
	if len(values) == 1 && strings.Contains(values[0], "-overlay") {
		return fmt.Errorf(
			"runtime overlay: GOFLAGS already contains -overlay (%q). Two overlays cannot both be the one that compiled "+
				"this artifact, so the build stops instead of letting the last flag win", values[0])
	}
	return nil
}

// EnvValues returns every value of one NAME in an environment slice, in order, so a caller can tell
// one entry from two.
func EnvValues(env []string, name string) []string {
	prefix := name + "="
	values := make([]string, 0, 2)
	for _, entry := range env {
		if strings.HasPrefix(entry, prefix) {
			values = append(values, strings.TrimPrefix(entry, prefix))
		}
	}
	return values
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", `'\''`) + "'"
}
